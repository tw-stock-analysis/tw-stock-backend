"""Explicit trading allowlist, based on TWSE's published OpenAPI categories.

No user-controlled upstream URLs. The website index was consulted on 2026-10-18;
live adapter verification is separate from inclusion in this catalogue.
"""

from app.schemas.twse import Category, TradingDataset, View

BASE_URL = "https://openapi.twse.com.tw/v1"


def resource(
    key: str,
    path: str,
    title: str,
    category: Category,
    view: View,
    description: str,
    search_hint: str = "搜尋代碼、名稱或資料內容",
) -> TradingDataset:
    return TradingDataset(
        id=key,
        path=path,
        title=title,
        category=category,
        view=view,
        description=description,
        search_hint=search_hint,
        source_url=BASE_URL + path,
        endpoint="/api/v1/twse" + path,
        page_path="/market/" + key,
    )


